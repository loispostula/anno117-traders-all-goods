#!/usr/bin/env python3
"""Generate mod/data/base/config/export/assets.xml from reference/goods.tsv.

The output is committed. The tests fail when it is out of date.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GOODS_TSV = ROOT / "reference/goods.tsv"
ASSETS = ROOT / "mod/data/base/config/export/assets.xml"

# NPC goods traders (3rd party participants with Trader/OfferedGoods).
# Not patched: Julia 41986 (campaign, GoodsTrader 0), Caecilia 145051 (Prophecies of Ash
# barter trader, items only) and Heron's sector project 182192 (no goods stock).
TRADERS = {
    "32777": "Diana (Latium)",
    "32778": "Valeria (Latium)",
    "27124": "Procurator (Albion)",
    "27079": "Manx (Albion)",
    "37495": "Caeso (Latium pirate)",
    "37494": "Voada (Albion pirate)",
    "153067": "Heron (Aegyptus, Dawn of the Delta)",
    "153068": "Valeria (Aegyptus, Dawn of the Delta)",
    "153069": "Kandis (Aegyptus pirate, Dawn of the Delta)",
}
# TradeBalancing: GenericTradeFeature/UnsellableGoodsByNonPlayerCharacters.
TRADE_FEATURE = "140115"
# Prophecies of Ash needs goods that vanilla forbids NPCs to sell. Obsidian (145102) stays forbidden.
UNBLOCKED = {"145220": "Statuettes", "145221": "Latrunculi Sets"}

# Final products added by other mods, only when that mod is active. GUIDs read from the mod's files.
MOD_GOODS = {
    "celtic-independence-overhaul-jtmzac": [  # Celtic Independence Overhaul 0.9.x
        ("1400300500", "Wicker Baskets"),
        ("1400300510", "Ornamented Ponies"),
    ],
}

# Stock for each added good: refill rate and stock cap. Vanilla traders use 0.25-0.5 / 15-75.
PRODUCTION_PER_MINUTE = "0.5"
LIMIT = "30"


def goods():
    lines = GOODS_TSV.read_text(encoding="utf-8").splitlines()[1:]
    return [line.split("\t")[:3] for line in lines if line.strip()]


def add(trader, guid, label, indent):
    return (f'{indent}<ModOp GUID="{trader}" AllowNoMatch="1" '
            f'Add="Trader/OfferedGoods/Item/Goods[not(Item/Good=\'{guid}\')]">'
            f"<Item><Good>{guid}</Good><ProductionPerMinute>{PRODUCTION_PER_MINUTE}</ProductionPerMinute>"
            f"<Limit>{LIMIT}</Limit></Item></ModOp>  <!-- {label} -->")


def render():
    out = [
        "<ModOps>",
        "  <!-- Generated by tools/generate.py from reference/goods.tsv. Do not edit by hand. -->",
        "",
        "  <!-- Let NPCs sell the Prophecies of Ash needs goods. -->",
    ]
    for guid, name in UNBLOCKED.items():
        out.append(f'  <ModOp GUID="{TRADE_FEATURE}" AllowNoMatch="1" '
                   f'Remove="GenericTradeFeature/UnsellableGoodsByNonPlayerCharacters/Item[Good=\'{guid}\']" />'
                   f"  <!-- {name} -->")
    for trader, label in TRADERS.items():
        out += [
            "",
            f"  <!-- {label}: every stock tier offers every final product. Goods already in a tier keep their vanilla values. -->",
            f'  <Group Condition="@{trader}/Trader/OfferedGoods/Item/Goods">',
        ]
        out += [add(trader, guid, english or name, "    ") for guid, name, english in goods()]
        for mod_id, mod_goods in MOD_GOODS.items():
            out.append(f'    <Group Condition="#{mod_id}">')
            out += [add(trader, guid, name, "      ") for guid, name in mod_goods]
            out.append("    </Group>")
        out.append("  </Group>")
    out.append("</ModOps>")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if ASSETS.read_text(encoding="utf-8") == text else "assets.xml is out of date")
    ASSETS.write_text(text, encoding="utf-8")
    print(ASSETS)
